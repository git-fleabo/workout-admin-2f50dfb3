function row(week: number, day: number, lesson: string, pattern: string, sets?: number[]): Day {
  if (pattern.startsWith("Flow ")) return [week, day, lesson, pattern, []];
  const doses = patterns[pattern];
  if (!doses || (sets && sets.length !== doses.length)) throw new Error("Invalid source row.");
  return [
    week,
    day,
    lesson,
    "",
    doses.map(([move, count, dose], i) => [move, sets?.[i] ?? count, dose]),
  ];
}

